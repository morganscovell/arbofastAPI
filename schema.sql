CREATE DATABASE IF NOT EXISTS `4g-tree`;

use `4g-tree`;

CREATE TABLE IF NOT EXISTS users(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) DEFAULT NULL,
    email VARCHAR(100) DEFAULT NULL UNIQUE,
    password VARCHAR(255) DEFAULT NULL,
    phone VARCHAR(20) DEFAULT NULL,    
    photo TEXT DEFAULT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    role ENUM('USER', 'ADMIN') NOT NULL DEFAULT 'USER',
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS oauth_accounts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    userId BIGINT UNSIGNED NOT NULL,
    provider ENUM('GOOGLE', 'APPLE') NOT NULL,
    providerUserId VARCHAR(255) NOT NULL,
    createdAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    UNIQUE KEY unique_provider_user (provider, providerUserId),
    CONSTRAINT fk_oauth_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS addresses(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    address TEXT DEFAULT NULL,    
    type VARCHAR(15) NOT NULL,
    isDefault BOOLEAN DEFAULT FALSE,
    userId BIGINT UNSIGNED NOT NULL,
    
    CONSTRAINT fk_address_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS mulch_requests(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    amountPreference ENUM('FULL', 'HALF', 'ANY') DEFAULT 'ANY',
    username VARCHAR(50) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    address TEXT NOT NULL,
    latitude DECIMAL(9,6) DEFAULT NULL,
    longitude DECIMAL(9,6) DEFAULT NULL,
    photoUrl TEXT DEFAULT NULL,
    instruction TEXT DEFAULT NULL,
    status ENUM('PENDING', 'DECLINED', 'APPROVED') DEFAULT 'PENDING',
    scheduledData Date DEFAULT NULL,
    scheduledTime TIME DEFAULT NULL,
    userId BIGINT UNSIGNED NOT NULL,

    CONSTRAINT fk_mulch_request_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS work_items(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    treeSpecie ENUM('NOT_SURE', 'OAK', 'PINE', 'REDWOOD', 'EUCALYPTUS', 'PALM', 'MAPLE', 'ELM', 'SYCAMORE',
        'COTTONWOOD', 'WILLOW', 'OLIVE', 'PEPPER_TREE', 'FRUIT_TREE', 'ORNAMENTAL_TREE', 'SHRUB/BUSH') NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    scopes JSON NOT NULL,
    raiseCanopyFeet INT DEFAULT NULL,
    crownReductionPercentage INT DEFAULT NULL,
    customServiceNote TEXT DEFAULT NULL,
    desiredTimeFrame TEXT DEFAULT NULL,
    noCleanUp BOOLEAN DEFAULT NULL,
    woodHandling ENUM('LEAVE', 'HAUL', 'CUT') DEFAULT NULL,
    woodLengthToBeCut DECIMAL(5,2) DEFAULT NULL,
    debrisHandling ENUM('LEAVE', 'HAUL') DEFAULT NULL,
    accessOption ENUM('FRONT_YARD', 'BACK_YARD', 'SIDE_YARD', 'NEAR_HOUSE', 'UNKNOWN') DEFAULT NULL,
    accessOptionNote TEXT DEFAULT NULL,
    laborCost DECIMAL(10,2) DEFAULT NULL,
    estimatedHours DECIMAL(5,2) DEFAULT NULL,
    note TEXT DEFAULT NULL 
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS work_item_images(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    url TEXT NOT NULL,
    type ENUM('FULL_VIEW', 'TRUNK/BASE', 'CROWN/CANOPY', 'STUMP', 'WORK_AREA') DEFAULT NULL,
    config TEXT DEFAULT NULL,
    workItemId BIGINT UNSIGNED DEFAULT NULL,

    CONSTRAINT fk_work_item FOREIGN KEY (workItemId) REFERENCES work_items(id) ON DELETE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS estimates(
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(30) NOT NULL,
    email VARCHAR(50) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address TEXT NOT NULL,
    latitude DECIMAL(9,6) DEFAULT NULL,
    longitude DECIMAL(9,6) DEFAULT NULL,
    status ENUM('PENDING', 'ACCEPTED', 'SENT_TO_QUICKBOOK', 'DRAFT', 'APPROVED') NOT NULL DEFAULT 'PENDING',
    noteOrInstruction TEXT DEFAULT NULL,
    userId BIGINT UNSIGNED DEFAULT NULL,
    equipmentOrCrewOptions JSON DEFAULT NULL,
    hazards JSON DEFAULT NULL,

    CONSTRAINT fk_estimate_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE 
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS estimate_work_items(
    estimateId BIGINT UNSIGNED NOT NULL,
    workItemId BIGINT UNSIGNED NOT NULL,

    PRIMARY KEY (estimateId, workItemId),
    CONSTRAINT fk_estimate_id FOREIGN KEY (estimateId) REFERENCES estimates(id) ON DELETE CASCADE,
    CONSTRAINT fk_work_item_id FOREIGN KEY (workItemId) REFERENCES work_items(id) ON DELETE CASCADE
)ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

/* TRIGGERS */

DELIMITER //

CREATE TRIGGER before_estimate_delete
BEFORE DELETE ON estimates
FOR EACH ROW
BEGIN
    DELETE wi
    FROM work_items wi
    JOIN estimate_work_items ewi
        ON wi.id = ewi.workItemId
    WHERE ewi.estimateId = OLD.id;
END;
//

DELIMITER ;